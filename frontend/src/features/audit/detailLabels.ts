/** Recorded values that are codes rather than words, per key. Anything else is shown as recorded. */
const VALUE_LABELS: Record<string, Record<string, string>> = {
  method: { password: 'Mật khẩu', google: 'Google' },
  mode: { Local: 'Máy local', Api: 'API' },
  apikey: { kept: 'Giữ nguyên', replaced: 'Thay mới', removed: 'Đã xoá' },
  source: { Upload: 'Tải lên', BrowserCapture: 'Ghi trên trình duyệt' },
}

export function detailLabel(key: string) {
  return KEY_LABELS[key.toLowerCase()] ?? key
}

/** A scalar value in words: yes/no for a boolean, a known code by its name, anything else as recorded. */
export function detailValue(key: string, value: string | number | boolean) {
  if (typeof value === 'boolean') return value ? 'Có' : 'Không'
  return VALUE_LABELS[key.toLowerCase()]?.[String(value)] ?? String(value)
}
